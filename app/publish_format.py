def _content_value(content: str, prefix: str) -> str:
    for line in content.splitlines():
        head = line.split(":", 1)[0].split("：", 1)[0]
        if line.startswith(prefix) or prefix in head:
            if "：" in line:
                return line.split("：", 1)[1].strip()
            if ":" in line:
                return line.split(":", 1)[1].strip()
    return ""


def _bi(en: str, cn: str) -> str:
    return f"{en} / {cn}"


def _section_lines(content: str, section_title: str, limit: int) -> List[str]:
    lines = content.splitlines()
    start = -1
    for index, line in enumerate(lines):
        if section_title == line.strip() or section_title in line:
            start = index + 1
            break
    if start < 0:
        return []
    selected: List[str] = []
    for line in lines[start:]:
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith(("I.", "II.", "III.", "IV.", "V.", "VI.", "VII.")):
            break
        selected.append(stripped)
        if len(selected) >= limit:
            break
    return selected


