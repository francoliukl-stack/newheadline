def entity_label(record: Dict[str, Any]) -> str:
    entities = [entity for entity in record_entities(record) if entity != "Other"]
    return ", ".join(entities) if entities else "Unclassified"


def change_type(record: Dict[str, Any]) -> str:
    fields = record.get("fields") or {}
    label = label_name(fields).lower()
    text = record_text(record)
    if label in {"funding", "m&a"} or any(hint in text for hint in FUNDING_HINTS):
        return "Capital / M&A"
    if label in {"earnings"} or is_metric_record(record):
        return "Scale / Performance"
    if any(word in text for word in ("launch", "product", "platform", "tool", "agent", "ai")):
        return "Product / Capability"
    if any(word in text for word in ("partner", "alliance", "collaboration", "integrat")):
        return "Partnership / Ecosystem"
    if any(word in text for word in ("regulation", "license", "compliance", "regulated")):
        return "Regulation / Compliance"
    return label_name(fields)


def strategic_implication(record: Dict[str, Any]) -> str:
    section = section_name(record)
    text = record_text(record)
    if section == "Contact Center":
        if any(word in text for word in ("secure", "regulated", "compliance", "fortanix", "nvidia")):
            return "Enterprise AI is moving toward secure, compliant and scalable deployment. / 企业级 AI 正从可用性走向安全、合规和规模化部署。"
        return "Voice and agentic AI are reshaping service interactions and operating efficiency. / Voice/Agentic AI 正在重塑服务交互和运营效率。"
    if any(word in text for word in ("agent", "programmable", "openai", "ai")):
        return "AI-agent scenarios are redefining payments and financial infrastructure. / AI agent 场景正在重定义支付和金融基础设施。"
    if any(word in text for word in ("global", "cross-border", "expand")):
        return "Cross-border and globalization capabilities keep expanding. / 跨境和全球化能力继续外溢。"
    if is_funding_record(record):
        return "Capital continues to price this capability direction. / 资本仍在为该能力方向定价。"
    return "Treat this as an industry weak signal for continued tracking. / 作为行业弱信号继续观察。"


def executive_priority(record: Dict[str, Any]) -> str:
    text = record_text(record)
    if any(word in text for word in ("visa", "openai", "stripe", "regulated", "nvidia", "deepgram")):
        return "P1"
    if is_funding_record(record) or is_metric_record(record):
        return "P1"
    return "P2"


