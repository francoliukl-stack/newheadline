def record_entities(record: Dict[str, Any]) -> List[str]:
    text = record_text(record)
    names = [
        entity for entity, aliases in COMPETITOR_ALIASES.items()
        if any(alias in text for alias in aliases)
    ]
    return names or ["Other"]


def first_source_link(record: Dict[str, Any]) -> str:
    fields = record.get("fields") or {}
    url = source_url(fields)
    if not url:
        return source_domain(field_text(fields.get("Source") or fields.get("Source Domain")))
    return f"[{source_domain(url)}]({url})"


def is_metric_record(record: Dict[str, Any]) -> bool:
    text = record_text(record)
    return any(hint in text for hint in METRIC_HINTS)


def is_funding_record(record: Dict[str, Any]) -> bool:
    fields = record.get("fields") or {}
    label = label_name(fields).lower()
    text = record_text(record)
    return label in {"funding", "m&a", "earnings"} or any(hint in text for hint in FUNDING_HINTS)


def section_name(record: Dict[str, Any]) -> str:
    fields = record.get("fields") or {}
    section = fields.get("Section")
    if section:
        return str(section)
    text = " ".join([
        str(fields.get("Title") or ""),
        str(fields.get("Title & URL") or ""),
        source_url(fields),
        str(fields.get("Source") or ""),
    ]).lower()
    if any(hint in text for hint in FINANCE_HINTS):
        return "Finance"
    if any(hint in text for hint in CONTACT_CENTER_HINTS):
        return "Contact Center"
    return "News"


def format_date_label(timestamp_ms: int) -> str:
    if not timestamp_ms:
        return ""
    return datetime.fromtimestamp(timestamp_ms / 1000).strftime("%b %d").upper()


def selected_date_range(records: Iterable[Dict[str, Any]], fallback: datetime) -> str:
    dates = [record_date(record) for record in records if record_date(record)]
    if not dates:
        return fallback.strftime("%b %d").upper()
    start = format_date_label(min(dates))
    end = format_date_label(max(dates))
    return start if start == end else f"{start} - {end}"


def ordered_sections(records: Iterable[Dict[str, Any]]) -> List[str]:
    sections: List[str] = []
    for record in records:
        section = section_name(record)
        if section not in sections:
            sections.append(section)
    ordered: List[str] = []
    for preferred in ("Finance", "Contact Center", "News"):
        if preferred in sections:
            ordered.append(preferred)
            sections.remove(preferred)
    return ordered + sections


def sorted_recent_records(records: Iterable[Dict[str, Any]]) -> List[Dict[str, Any]]:
    return sorted(records, key=lambda record: (-record_date(record), str(record.get("id") or "")))


def business_signal(record: Dict[str, Any]) -> str:
    fields = record.get("fields") or {}
    label = label_name(fields)
    headline = concise_headline(fields.get("Title") or fields.get("Title & URL") or "-")
    return f"{label}: {headline}"


def top_entity_records(records: List[Dict[str, Any]], limit: int = 8) -> List[Tuple[str, List[Dict[str, Any]]]]:
    grouped: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for record in sorted_recent_records(records):
        for entity in record_entities(record):
            grouped[entity].append(record)
    ranked = sorted(grouped.items(), key=lambda item: (item[0] == "Other", -len(item[1]), item[0]))
    return ranked[:limit]


def markdown_cell(value: Any) -> str:
    if value is None:
        return "-"
    return str(value).replace("|", "/").replace("\n", " ").strip() or "-"


def markdown_table(headers: List[str], rows: List[List[Any]]) -> List[str]:
    lines = [
        "| " + " | ".join(markdown_cell(header) for header in headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(markdown_cell(value) for value in row) + " |")
    return lines


