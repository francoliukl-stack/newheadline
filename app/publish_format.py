def is_accepted_record(record: Dict[str, Any], field_mapping: Dict[str, str]) -> bool:
    return status_name(record.get("fields") or {}, field_mapping) == "已采纳"


def numeric_date(value: Any) -> int:
    if isinstance(value, (int, float)):
        return int(value)
    if isinstance(value, str):
        stripped = value.strip()
        if stripped.isdigit():
            return int(stripped)
        for fmt in ("%Y-%m-%d", "%Y/%m/%d"):
            try:
                return int(datetime.strptime(stripped, fmt).timestamp() * 1000)
            except ValueError:
                continue
    return 0


def record_date(record: Dict[str, Any]) -> int:
    fields = record.get("fields") or {}
    return numeric_date(fields.get("Publish Date")) or numeric_date(fields.get("First Seen At"))


def record_sort_key(record: Dict[str, Any]) -> Tuple[str, int, str]:
    return (
        section_name(record),
        -record_date(record),
        str(record.get("id") or ""),
    )


def source_url(fields: Dict[str, Any]) -> str:
    value = fields.get("Source URL") or {}
    if isinstance(value, dict):
        return str(value.get("link") or value.get("text") or "")
    return str(value or "")


def source_domain(url: str) -> str:
    parsed = urlparse(url)
    return parsed.netloc.lower().removeprefix("www.") or url


def field_text(value: Any) -> str:
    if isinstance(value, dict):
        return str(value.get("name") or value.get("text") or value.get("link") or "")
    if isinstance(value, list):
        return ", ".join(field_text(item) for item in value if field_text(item))
    return str(value or "")


def concise_headline(value: Any) -> str:
    text = str(value or "-").strip()
    if " | " in text:
        parts = [part.strip() for part in text.split(" | ") if part.strip()]
        text = parts[0]
        latin_words = lambda part: re.findall(r"[A-Za-z][A-Za-z0-9+&'-]*", part)
        translated = [part for part in parts[1:] if len(latin_words(part)) >= 5]
        if len(latin_words(text)) < 4 and translated:
            text = max(translated, key=lambda part: len(latin_words(part)))
    words = text.split()
    if len(words) <= MAX_HEADLINE_WORDS:
        return text
    return " ".join(words[:MAX_HEADLINE_WORDS]).rstrip(".,;:") + "..."


def record_text(record: Dict[str, Any]) -> str:
    fields = record.get("fields") or {}
    values = [
        fields.get("Title"),
        fields.get("Title & URL"),
        fields.get("Label"),
        fields.get("Tag"),
        fields.get("Section"),
        fields.get("Source"),
        fields.get("Source Domain"),
        source_url(fields),
    ]
    return " ".join(field_text(value) for value in values).lower()


