def build_headlines_content(
    records: List[Dict[str, Any]],
    cadence: str,
    range_label: str,
    details_url: Optional[str] = None,
    max_items_per_section: Optional[int] = None,
) -> str:
    rocket = "\U0001f680"
    bullet = "\u2022"
    title = "Finance & Contact Center Daily Report" if cadence.lower() == "daily" else f"Finance & Contact Center {cadence} Headlines"
    lines = [title]
    for section in ordered_sections(records):
        section_records = sorted([
            record for record in records
            if section_name(record) == section
        ], key=record_sort_key)
        if max_items_per_section:
            section_records = section_records[:max_items_per_section]
        if not section_records:
            continue
        lines.extend(["", f"[{rocket}] {SECTION_TITLES.get(section, section)}", ""])
        for record in section_records:
            fields = record.get("fields") or {}
            url = source_url(fields)
            headline = concise_headline(fields.get("Title") or fields.get("Title & URL") or "-")
            label = fields.get("Label") or fields.get("Tag") or "News"
            source = f" ([{source_domain(url)}]({url}))" if url else ""
            lines.append(f"{bullet}  {label}: {headline}{source}  ")
            publish_date = field_text(fields.get("Publish Date")) or "-"
            lines.append(f"   Publish Date: {publish_date}  ")
            event_id = field_text(fields.get("Event ID"))
            if event_id and cadence.lower() != "daily":
                event_sources = field_text(fields.get("Event Source IDs")) or "-"
                evidence_ids = field_text(fields.get("Evidence IDs")) or "-"
                claim_ids = field_text(fields.get("Claim IDs")) or "-"
                lines.append(
                    f"   ↳ Event {event_id} | Event Source {event_sources} | "
                    f"Evidence {evidence_ids} | Claim {claim_ids}  "
                )
    includes_deadline_fallback = any(
        "AI_Deadline" in field_text((record.get("fields") or {}).get("Review Decision Sources"))
        for record in records
    )
    lines.extend(["", "--------------------------", AI_DEADLINE_NOTE if includes_deadline_fallback else NOTE])
    return "\n".join(lines)


def build_weekly_research_link_content(
    records: List[Dict[str, Any]],
    range_label: str,
    research_topic: str,
    research_document_url: str,
    max_items_per_section: Optional[int] = None,
) -> str:
    if not str(research_document_url or "").startswith(("https://", "http://")):
        raise ValueError("a valid Research Document URL is required")
    digest_records = [
        {
            **record,
            "fields": {
                key: value for key, value in (record.get("fields") or {}).items()
                if key not in {"Event ID", "Event Source IDs", "Evidence IDs", "Claim IDs"}
            },
        }
        for record in records
    ]
    digest = build_headlines_content(digest_records, "Weekly", range_label, max_items_per_section=max_items_per_section)
    digest_lines = digest.splitlines()
    if digest_lines:
        digest_lines = digest_lines[1:]
    return "\n".join([
        "GBSS Weekly AI & Service Intelligence",
        "",
        f"Period: {range_label}",
        f"Research Focus: {research_topic or 'GBSS Weekly Deep Research'}",
        f"Deep Research Report: [Open DingTalk document]({research_document_url})",
        "",
        "Weekly Key Events & News",
        *digest_lines,
    ])


